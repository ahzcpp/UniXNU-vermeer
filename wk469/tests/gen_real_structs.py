#!/usr/bin/env python3
# Extract the ACTUAL struct definitions this observer depends on from an xnu-10063.141.1 tree (read-only) into
# tests/real_structs.inc, so abi_real.c / parse_test.c compile the real field lists (not our mirror) on the host.
# Usage: gen_real_structs.py <xnu-root>. The tree may be the public apple-oss-distributions/xnu tag xnu-10063.141.1
# (commit d8b80295118ef25ac3a784134bcf95cd8e88109f); every input file must match the pinned sha256 below.
import hashlib, re, sys
from pathlib import Path

if len(sys.argv) != 2: raise SystemExit('usage: gen_real_structs.py <xnu-root>')
X = Path(sys.argv[1])
PINNED = {
    'bsd/sys/socketvar.h': 'c2f26cd7374a714a52b5378d566be5e7091603252a22e5381fb79e6cf638d0c9',
    'bsd/netinet/in_pcb.h': 'b9b0214589fd9fb140d98dfc9de3ebac3001c833331ee80b0691fc6ae0a469cf',
    'bsd/netinet/tcp_var.h': '70b567e5d89036e6c02d6c50389f00230600009efe54021e6d04c561ba425369',
    'bsd/sys/stackshot.h': 'dde587e7300a8845eaa534034f33990357f1d9c332867cd9b35b837dcd16ba77',
    'osfmk/kern/kcdata.h': '784a0d82bb861eec54f825d60af4b81ec8dd9142993ad9745f4d6273afa2e2cf',
}
for rel, want in PINNED.items():
    got = hashlib.sha256((X / rel).read_bytes()).hexdigest()
    if got != want: raise SystemExit(f'pinned header mismatch {rel} {got}')
OUT = Path(__file__).resolve().parent / 'real_structs.inc'
WANT = [
    ('bsd/sys/socketvar.h', 'struct data_stats {', None),
    ('bsd/sys/socketvar.h', 'struct  xsocket_n {', 'pack4'),
    ('bsd/sys/socketvar.h', 'struct xsockbuf_n {', 'pack4'),
    ('bsd/sys/socketvar.h', 'struct xsockstat_n {', 'pack4'),
    ('bsd/netinet/in_pcb.h', 'struct  xinpcb_n {', 'pack4'),
    ('bsd/netinet/in_pcb.h', 'struct  xinpgen {', 'pack4'),
    ('bsd/netinet/tcp_var.h', 'struct  xtcpcb_n {', 'pack4'),
    ('bsd/sys/stackshot.h', 'typedef struct stackshot_config {', None),
    ('osfmk/kern/kcdata.h', 'struct task_snapshot_v2 {', None),
    ('osfmk/kern/kcdata.h', 'struct thread_snapshot_v4 {', None),
    ('osfmk/kern/kcdata.h', 'typedef struct stackshot_thread_waitinfo_v2 {', None),
    ('osfmk/kern/kcdata.h', 'typedef struct stackshot_thread_turnstileinfo_v2 {', None),
    ('osfmk/kern/kcdata.h', 'struct dyld_uuid_info_64 {', None),
    ('osfmk/kern/kcdata.h', 'struct dyld_shared_cache_loadinfo {', None),
    ('osfmk/kern/kcdata.h', 'struct kcdata_item {', None),
]
PRELUDE = '''/* GENERATED by gen_real_structs.py from the real xnu-10063.141.1 headers; host test only. */
#include <stdint.h>
typedef uint8_t u_char; typedef uint16_t u_short; typedef uint32_t u_int; typedef uint32_t u_int32_t;
typedef uint64_t u_int64_t; typedef uint64_t u_quad_t; typedef uint8_t u_int8_t; typedef uint16_t u_int16_t;
typedef int32_t pid_t_; typedef uint32_t uid_t_; typedef u_quad_t so_gen_t; typedef u_quad_t inp_gen_t;
typedef uint32_t tcp_seq; typedef uint32_t tcp_cc; typedef unsigned char uuid_t_[16];
#define pid_t pid_t_
#define uid_t uid_t_
#define uuid_t uuid_t_
struct in_addr { uint32_t s_addr; };
struct in6_addr { uint8_t s6_addr[16]; };
struct in_addr_4in6 { u_int32_t ia46_pad32[3]; struct in_addr ia46_addr4; };
#define SO_TC_STATS_MAX 4
#define TCPT_NTIMERS_EXT 4
'''
def grab(text, start):
    i = text.index(start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == '{': depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0:
                k = text.index(';', j)
                return text[i:k + 1]
    raise SystemExit('unterminated ' + start)
parts, ids = [PRELUDE], []
for rel, start, mode in WANT:
    t = (X / rel).read_text()
    s = grab(t, start)
    s = re.sub(r'#define [^\n]*\n', '\n', s)          # in-struct flag macros
    ids.append((rel, hashlib.sha256((X / rel).read_bytes()).hexdigest()[:16], start))
    parts.append(('#pragma pack(4)\n' + s + '\n#pragma pack()\n') if mode == 'pack4' else (s + '\n'))
OUT.write_text('\n'.join(parts))
for r in ids: print('source', *r)
print('wrote', OUT, hashlib.sha256(OUT.read_bytes()).hexdigest()[:16])
